# For each incident, estimate pairwise temporal precedence from model-predicted
# authenticity and claimed timestamps. This baseline ranks evidence; it is not causal proof.
def reconstruct_timeline(incident_id, split="test"):
    rows=splits[split]
    idx=[i for i,r in enumerate(rows) if r["incident_id"]==incident_id]
    if not idx: return None
    feats=FEATURES[split][0][idx]
    subset=[rows[i] for i in idx]
    # Sort by claimed timestamp, but flag low authenticity confidence.
    x=torch.tensor(feats,dtype=torch.float32,device=DEVICE)
    # Build complete local graph
    n=len(idx); pairs=[(i,j) for i in range(n) for j in range(n) if i!=j]
    edge=torch.tensor(pairs,dtype=torch.long,device=DEVICE).T
    graph_model.eval()
    with torch.no_grad():
        _,auth,role,edge_logits=graph_model(x,edge)
    ranked=[]
    for i,r in enumerate(subset):
        ranked.append({
            "evidence_id":r["evidence_id"],
            "claimed_timestamp":r["claimed_timestamp"],
            "authenticity_estimate":float(auth[i].cpu()),
            "relevance_prediction":int(role[i].argmax().cpu()),
            "review_flag":bool(auth[i].cpu()<0.5)
        })
    ranked.sort(key=lambda z:z["claimed_timestamp"])
    return ranked

