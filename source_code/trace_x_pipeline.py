# Measures how much the incident-level mean relevance confidence changes
# when one evidence node is removed. This is a sensitivity explanation, not causal proof.
def explain_incident(incident_id, split="test"):
    rows=splits[split]
    idx=[i for i,r in enumerate(rows) if r["incident_id"]==incident_id]
    if len(idx)<2: return []
    x=FEATURES[split][0][idx]
    def score(arr):
        n=len(arr); pairs=[(i,j) for i in range(n) for j in range(n) if i!=j]
        if not pairs: return 0.0
        et=torch.tensor(pairs,dtype=torch.long,device=DEVICE).T
        with torch.no_grad():
            _,_,role,_=graph_model(torch.tensor(arr,dtype=torch.float32,device=DEVICE),et)
            return float(torch.softmax(role,1)[:,1].mean().cpu())
    base=score(x); output=[]
    for k,ridx in enumerate(idx):
        reduced=np.delete(x,k,axis=0)
        output.append({"removed_evidence":rows[ridx]["evidence_id"],
                       "confidence_change":base-score(reduced)})
    return sorted(output,key=lambda z:abs(z["confidence_change"]),reverse=True)

