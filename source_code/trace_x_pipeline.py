WORDS = ["meeting","delivery","message","door","vehicle","location","package","camera","call",
         "arrival","departure","report","account","access","system","alert","witness","record",
         "changed","missing","confirmed","unknown","urgent","normal","review","timeline"]
def make_text(event_id, incident_id, variant, forged):
    rng = random.Random(incident_id*1000 + event_id*10 + variant)
    tokens = rng.sample(WORDS, 7)
    if forged: tokens += ["altered","unverified"]
    return " ".join(tokens)

def make_image_pattern(event_id, incident_id, forged, variant):
    # Controlled geometric pattern; not a real-world image-forensics dataset.
    rng = np.random.default_rng(incident_id*1000 + event_id*10 + variant)
    img = np.zeros((1, IMAGE_SIZE, IMAGE_SIZE), dtype=np.float32)
    yy, xx = np.mgrid[:IMAGE_SIZE, :IMAGE_SIZE]
    cx, cy = rng.integers(8,24,size=2)
    radius = rng.integers(4,9)
    img[0][(xx-cx)**2 + (yy-cy)**2 < radius**2] = 0.8
    x0, y0 = rng.integers(0,20,size=2)
    img[0,y0:y0+5,x0:x0+9] = 0.4
    if forged: img[0] = np.roll(img[0], shift=3, axis=1)
    img += rng.normal(0,0.04,img.shape).astype(np.float32)
    return np.clip(img,0,1)

