def build_vocab(rows, max_vocab=VOCAB_SIZE):
    counts=Counter()
    for r in rows: counts.update(r["text"].lower().split())
    vocab={"<pad>":0,"<unk>":1}
    for w,_ in counts.most_common(max_vocab-2): vocab[w]=len(vocab)
    return vocab
