# A lightweight message-passing network implemented in plain PyTorch.
# Nodes are evidence items. Edges connect items from the same incident.
# Authenticity gate scales each source node's outgoing message.
class TraceGraphNet(nn.Module):
    def __init__(self, in_dim=193, hidden=96):
        super().__init__()
        self.node=nn.Sequential(nn.Linear(in_dim,hidden),nn.ReLU(),nn.Dropout(0.15))
        self.msg=nn.Linear(hidden,hidden)
        self.update=nn.GRUCell(hidden,hidden)
        self.auth=nn.Linear(hidden,1)
        self.role=nn.Linear(hidden,2)  # relevant / distractor
        self.edge=nn.Sequential(nn.Linear(hidden*4,hidden),nn.ReLU(),nn.Linear(hidden,2))
    def forward(self,x,edge_index):
        h=self.node(x)
        auth=torch.sigmoid(self.auth(h)).squeeze(1)
        agg=torch.zeros_like(h); deg=torch.zeros((len(h),1),device=h.device)
        src,dst=edge_index
        messages=self.msg(h[src])*auth[src,None]
        agg.index_add_(0,dst,messages); deg.index_add_(0,dst,torch.ones((len(dst),1),device=h.device))
        h2=self.update(agg/(deg+1e-6),h)
        role=self.role(h2)
        a,b=h2[src],h2[dst]
        edge_logits=self.edge(torch.cat([a,b,torch.abs(a-b),a*b],dim=1))
        return h2,auth,role,edge_logits

# Build graph batches incident-by-incident, with fully-connected directed edges per incident.
def graph_examples(split):
    rows=splits[split]; feats=FEATURES[split][0]; examples=[]
    groups=defaultdict(list)
    for i,r in enumerate(rows): groups[r["incident_id"]].append(i)
    for inc,idxs in groups.items():
        idxs=np.array(idxs); x=feats[idxs]
        local={g:i for i,g in enumerate(idxs)}
        pairs=[(i,j) for i in range(len(idxs)) for j in range(len(idxs)) if i!=j]
        edge=np.array(pairs,dtype=np.int64).T
        yrole=np.array([1 if rows[g]["ground_truth"]["relevant"] else 0 for g in idxs],dtype=np.int64)
        yauth=np.array([rows[g]["ground_truth"]["forged"] for g in idxs],dtype=np.float32)
        yedge=[]
        for i,j in pairs:
            ri,rj=rows[idxs[i]],rows[idxs[j]]
            related=int(ri["event_id"]>=0 and ri["event_id"]==rj["event_id"])
            contradiction=int(related and ri["claimed_timestamp"]//1800 != rj["claimed_timestamp"]//1800)
            yedge.append(1 if contradiction else related) # 0 none, 1 related/contradictory candidate
        examples.append((x,edge,yrole,yauth,np.array(yedge,dtype=np.int64)))
    return examples

class GraphWrapper(nn.Module):
    def __init__(self): super().__init__(); self.net=TraceGraphNet()
    def forward(self,*args): return self.net(*args)

